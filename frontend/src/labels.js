// Сарын WAPE-ээс ойлгомжтой үнэлгээ; суурь аргатай харьцуулалт өгвөл түүнийг ч тооцно
export function accuracyLevel(wape, baseline) {
  if (wape === null || wape === undefined) return { label: "Үнэлэх боломжгүй", tone: "", text: "Шалгах өгөгдөл хүрэлцээгүй." };
  const better = baseline === null || baseline === undefined || wape < baseline;
  if (wape < 0.2 && better) return { label: "Сайн", tone: "ok", text: `Сарын алдаа ${(wape * 100).toFixed(0)}% — найдвартай.` };
  if (wape < 0.4 && better) return { label: "Дунд", tone: "warn", text: `Сарын алдаа ${(wape * 100).toFixed(0)}% — чиг хандлагыг зөв харуулна, нарийн тоонд болгоомжтой.` };
  return { label: "Сул", tone: "bad", text: better ? `Сарын алдаа ${(wape * 100).toFixed(0)}% — өндөр.` : "Энгийн аргаас илүү биш — таамаглалыг болгоомжтой ашиглана уу." };
}

