// Хассан шалтгааныг энгийн болгох: "бүтэн сар 6 < 24" → "түүх 6 сар (24 сар хэрэгтэй)"
export function plainExclude(reason) {
  const r = String(reason || "");
  const m = r.match(/бүтэн сар (\d+) < (\d+)/);
  if (m) return `Түүх богино: ${m[1]} сар (хамгийн багадаа ${m[2]} сар хэрэгтэй)`;
  if (r.startsWith("дэд багцад")) return "Энэ удаа шалгах бараанд сонгогдоогүй (барааны дээд тоо)";
  return r;
}
